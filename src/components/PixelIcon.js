export default function PixelIcon({ name, className, title }) {
  const rows = SPRITES[name] || SPRITES.star;
  const size = rows.length;
  const pixels = [];

  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c === '#' || c === '+') {
        pixels.push(
          <rect
            key={`${x}-${y}`}
            x={x}
            y={y}
            width="1.02"
            height="1.02"
            opacity={c === '+' ? 0.5 : 1}
          />
        );
      }
    }
  });

  return (
    <svg
      viewBox={`0 0 ${size} ${size}`}
      className={className}
      fill="currentColor"
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
    >
      {pixels}
    </svg>
  );
}
